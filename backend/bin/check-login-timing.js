#!/usr/bin/env node
import 'dotenv/config';
import { performance } from 'perf_hooks';
import request from 'supertest';
import { app } from '../src/server.js';
import { db } from '../src/config/db.js';
import { users, authRateLimits } from '../src/models/index.js';
import { eq } from 'drizzle-orm';
import { pool } from '../src/config/db.js';
import bcrypt from 'bcryptjs';

const ITERATIONS = parseInt(process.env.TIMING_ITERATIONS || '10', 10);

async function main() {
  console.log(`⏱️  Measuring login timing over ${ITERATIONS} iterations...`);

  // Ensure a test user exists
  const testUsername = 'timing_test_user';
  let [user] = await db.select().from(users).where(eq(users.username, testUsername));
  if (!user) {
    const salt = await bcrypt.genSalt(10);
    const passwordHash = await bcrypt.hash('CorrectPassword123!', salt);
    [user] = await db.insert(users).values({
      name: 'Timing Test User',
      username: testUsername,
      passwordHash,
      role: 'user',
      isActive: true,
    }).returning();
  }

  const existingTimes = [];
  const nonExistentTimes = [];

  for (let i = 0; i < ITERATIONS; i++) {
    const ipExisting = `10.0.1.${i + 1}`;
    const ipNonExistent = `10.0.2.${i + 1}`;

    // Test non-existent user
    const startNonExistent = performance.now();
    await request(app)
      .post('/api/auth/login')
      .set('X-Forwarded-For', ipNonExistent)
      .send({ username: `ghost_user_${Date.now()}_${i}`, password: 'WrongPassword123!' });
    const elapsedNonExistent = performance.now() - startNonExistent;
    nonExistentTimes.push(elapsedNonExistent);

    // Test existing user with wrong password
    const startExisting = performance.now();
    await request(app)
      .post('/api/auth/login')
      .set('X-Forwarded-For', ipExisting)
      .send({ username: testUsername, password: 'WrongPassword123!' });
    const elapsedExisting = performance.now() - startExisting;
    existingTimes.push(elapsedExisting);
  }

  // Cleanup rate limits generated by test
  try {
    await db.delete(authRateLimits);
  } catch (err) {
    // ignore
  }

  const avg = (arr) => (arr.reduce((a, b) => a + b, 0) / arr.length).toFixed(2);
  const min = (arr) => Math.min(...arr).toFixed(2);
  const max = (arr) => Math.max(...arr).toFixed(2);

  console.log('\n--- LOGIN TIMING RESULTS ---');
  console.log(`Non-existent user (N=${ITERATIONS}): avg=${avg(nonExistentTimes)}ms (min=${min(nonExistentTimes)}ms, max=${max(nonExistentTimes)}ms)`);
  console.log(`Existing user bad pw (N=${ITERATIONS}): avg=${avg(existingTimes)}ms (min=${min(existingTimes)}ms, max=${max(existingTimes)}ms)`);
  const diff = Math.abs(parseFloat(avg(nonExistentTimes)) - parseFloat(avg(existingTimes))).toFixed(2);
  console.log(`Difference in averages: ${diff}ms`);

  await pool.end();
  process.exit(0);
}

main().catch((err) => {
  console.error('Timing check failed:', err);
  process.exit(1);
});
